-- TCFFL registration database (Cloudflare D1 / SQLite)
-- Run once after creating the database:  npx wrangler d1 execute gcoys-registrations --remote --file=schema.sql
-- (or paste this whole file into the D1 "Console" tab in the Cloudflare dashboard)

CREATE TABLE IF NOT EXISTS registrations (
  id                      TEXT PRIMARY KEY,           -- e.g. TCFFL-2026-K7P2QX (server generated, not sequential)
  idempotency_key         TEXT NOT NULL UNIQUE,       -- generated by the browser; makes retries safe
  dup_key                 TEXT NOT NULL,              -- lower(first|last|dob|guardian email) to catch re-submissions
  created_at              TEXT NOT NULL,              -- server timestamp (UTC, ISO 8601)
  updated_at              TEXT NOT NULL,

  -- player
  first_name              TEXT NOT NULL,
  last_name               TEXT NOT NULL,
  dob                     TEXT NOT NULL,
  division                TEXT NOT NULL,
  grade                   TEXT NOT NULL,
  school                  TEXT NOT NULL,
  jersey_size             TEXT NOT NULL,

  -- parent / guardian
  guardian_name           TEXT NOT NULL,
  email                   TEXT NOT NULL,
  phone                   TEXT NOT NULL,
  address                 TEXT NOT NULL,

  -- emergency + medical (restricted: only returned by the admin API with the medical token)
  emergency_name          TEXT NOT NULL,
  emergency_relationship  TEXT NOT NULL,
  emergency_phone         TEXT NOT NULL,
  medical                 TEXT NOT NULL DEFAULT '',
  accommodations          TEXT NOT NULL DEFAULT '',

  -- league
  experience              TEXT NOT NULL DEFAULT '',
  position                TEXT NOT NULL DEFAULT '',
  team_request            TEXT NOT NULL DEFAULT '',

  -- consent (what was agreed to, which version of the text, and when)
  consent_version         TEXT NOT NULL,
  waiver                  INTEGER NOT NULL,
  medical_authorization   INTEGER NOT NULL,
  code_of_conduct         INTEGER NOT NULL,
  guardian_confirmation   INTEGER NOT NULL,
  media_permission        INTEGER NOT NULL DEFAULT 0,
  signature               TEXT NOT NULL,
  signed_date             TEXT NOT NULL,              -- date typed by the guardian
  -- (created_at above is the authoritative server-side time of signing)

  -- payment (families can never set these; only the server and verified Square webhooks do)
  scholarship_requested   INTEGER NOT NULL DEFAULT 0,
  payment_status          TEXT NOT NULL,              -- pending_payment | paid | failed | refunded | partial_refund | scholarship_review
  fee_cents               INTEGER NOT NULL,
  checkout_url            TEXT,
  square_payment_link_id  TEXT,
  square_order_id         TEXT,
  square_payment_id       TEXT,
  paid_at                 TEXT,
  payment_error           TEXT
);

CREATE INDEX IF NOT EXISTS idx_reg_dup   ON registrations (dup_key);
CREATE INDEX IF NOT EXISTS idx_reg_order ON registrations (square_order_id);
CREATE INDEX IF NOT EXISTS idx_reg_pay   ON registrations (square_payment_id);

-- Square sends each webhook event at least once; this table makes processing idempotent.
CREATE TABLE IF NOT EXISTS webhook_events (
  event_id     TEXT PRIMARY KEY,
  type         TEXT,
  received_at  TEXT NOT NULL,
  note         TEXT
);

-- Tiny per-IP throttle (hashed IPs only) for abuse protection.
CREATE TABLE IF NOT EXISTS rate_events (
  ip_hash TEXT NOT NULL,
  at      INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rate ON rate_events (ip_hash, at);
